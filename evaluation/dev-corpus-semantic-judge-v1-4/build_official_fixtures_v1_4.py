def norm(s):
    return re.sub(r"\s+", " ", s.strip().lower())


def load_burned_texts():
    texts = []
    paths = list(HERE.glob("*.json"))
    for d in sorted(ROOT.glob("dev-corpus-semantic-judge-v1-*")):
        paths.extend(d.glob("*.json"))
    seen = set()
    for p in paths:
        rp = p.resolve()
        if rp in seen or p.name == "official-validation-fixtures.json":
            continue
        seen.add(rp)
        try:
            data = json.loads(p.read_text())
        except Exception:
            continue
        stack = [data]
        while stack:
            item = stack.pop()
            if isinstance(item, str):
                if len(item) >= 20:
                    texts.append(norm(item))
            elif isinstance(item, dict):
                stack.extend(item.values())
            elif isinstance(item, list):
                stack.extend(item)
    return texts


def main():
    fixtures = CRITICAL + FORBIDDEN + ROUTE + UNCERTAINTY
    counts = {}
    for f in fixtures:
        counts[f["dimension"]] = counts.get(f["dimension"], 0) + 1
    ids = [f["id"] for f in fixtures]
    assert len(fixtures) == 100, f"expected 100 fixtures, got {len(fixtures)}"
    assert len(set(ids)) == len(ids), "duplicate ids"
    for dim, n in [("critical_condition", 25), ("forbidden_claim", 25),
                   ("route_correctness", 25), ("required_uncertainty", 25)]:
        assert counts.get(dim) == n, f"{dim}: expected 25, got {counts.get(dim)}"
    answers = [norm(f["sut_answer"]) for f in fixtures]
    assert len(set(answers)) == len(answers), "duplicate sut_answer text"
    burned = load_burned_texts()
    collisions = []
    for f in fixtures:
        a = norm(f["sut_answer"])
        for b in burned:
            if (len(b) > 30 and (b in a or a in b)) or a == b:
                collisions.append({"fixture": f["id"], "burned_fragment": b[:80]})
                break
    doc = {
        "set": "V1.4 official validation fixtures (fresh; frozen before human gold labeling)",
        "preregistration": {"fixture_count": 100, "distribution": counts,
                            "freshness_check": "mechanical collision scan over burned JSON artifacts",
                            "max_tokens": 32768},
        "freshness_collisions": collisions,
        "fixtures": fixtures,
    }
    out = HERE / "official-validation-fixtures.json"
    out.write_text(json.dumps(doc, indent=2, ensure_ascii=True) + "\n")
    print(f"wrote {out}: n={len(fixtures)} counts={counts} collisions={len(collisions)}")


if __name__ == "__main__":
    main()
