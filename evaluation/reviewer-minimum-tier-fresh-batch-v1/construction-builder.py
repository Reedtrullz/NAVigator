rows = []

def canon_hash(dimension, ctx, criterion, text):
    payload = json.dumps({
        "contract_version": CONTRACT_VERSION,
        "dimension": dimension,
        "case_context": ctx,
        "criterion": criterion,
        "sut_output": text,
    }, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()

def add(gid, fam, dim, safety, tags, ctx, criterion, text, srcs):
    n = sum(1 for r in rows if r["primary_family"] == fam)
    row_id = "FB1-%s-%03d" % (fam_code(fam), n + 1)
    rows.append({
        "row_id": row_id,
        "scenario_group_id": gid,
        "contract_version": CONTRACT_VERSION,
        "primary_family": fam,
        "property_tags": tags,
        "safety_critical": safety,
        "dimension": dim,
        "source_ids": srcs,
        "packet": {
            "case_context": ctx,
            "criterion": criterion,
            "sut_output": text,
            "reviewer_instructions": SAFE_INSTRUCTIONS if dim == "critical_condition" else CRIT_INSTRUCTIONS,
            "result_schema": SAFE_SCHEMA if dim == "critical_condition" else CRIT_SCHEMA,
            "canonical_hash": canon_hash(dim, ctx, criterion, text),
        },
    })

def fam_code(fam):
    return {
        "assertion_mention_attribution": "ASM",
        "safety_critical_rule_trigger_boundary": "SCR",
        "actor_referral_distinction": "ARD",
        "negation_polarity": "NGP",
        "insufficient_ambiguous_context": "IAC",
        "exception_condition_clauses": "EXC",
        "compound_conditions": "CMP",
        "simple_control": "CTL",
    }[fam]

def packet_for(row):
    p = row["packet"]
    return {
        "contract_version": row["contract_version"],
        "dimension": row["dimension"],
        "case_context": p["case_context"],
        "criterion": p["criterion"],
        "sut_output": p["sut_output"],
        "reviewer_instructions": p["reviewer_instructions"],
        "result_schema": p["result_schema"],
        "canonical_hash": p["canonical_hash"],
    }

