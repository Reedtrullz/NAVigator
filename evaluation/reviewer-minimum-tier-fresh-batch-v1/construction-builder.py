    build_assertion(); build_safety(); build_actor(); build_negation()
    build_insufficient(); build_exception(); build_compound(); build_control()
    rows.sort(key=lambda r: r["row_id"])
    with open(OUT_DATASET, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n")
